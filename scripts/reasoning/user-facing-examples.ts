/**
 * PR #105: before/after examples and performance for USER_FACING_REASONING_V1, on real deterministic
 * charts (the seed-99 sample). Read only. Writes docs/reasoning/PR105_BEFORE_AFTER.md.
 *
 *   npx tsx scripts/reasoning/user-facing-examples.ts
 *
 * "Before" is what the app shows today (the verdict, its conclusion, the evidence sheet's lines, the yoga
 * list, the period's why-it-matters line). "After" is the explanation layer. Ask and report examples are
 * the deterministic grounding text added to the prompt, not live AI output (none is generated here).
 */
import { writeFileSync } from 'fs';
import { performance } from 'perf_hooks';
import { resolveBirthWithCoordinates } from '../../server/astroEngine/birthResolver';
import { computeCanonicalChart } from '../../server/astroEngine/canonical/compute';
import { buildInsights } from '../../server/astroEngine/evidence/insights';
import { buildInterpretationContext } from '../../server/astroEngine/reasoning/interpretationContext';
import { buildExplanations, groundingBlock, sectionGroundingBlock } from '../../server/astroEngine/reasoning/explanations';
import { LIFE_REPORT_GROUNDING_PLAN } from '../../server/aiAstrologerService';
import { buildEvidencePacket, routeQuestion } from '../../server/agents/askKundli';
import type { CanonicalChart } from '../../shared/v3/canonical';
import type { LifeDomain } from '../../shared/v3/evidence';

const asOf = new Date('2026-10-13T06:00:00Z');
const PLACES: Array<[number, number]> = [[28.6139, 77.209], [19.076, 72.8777], [13.0827, 80.2707], [22.5726, 88.3639], [26.9124, 75.7873], [51.5074, -0.1278], [40.7128, -74.006], [-33.8688, 151.2093], [1.3521, 103.8198]];
const pad = (n: number) => String(n).padStart(2, '0');

function sample() {
  let seed = 99; const rnd = () => ((seed = (seed * 1103515245 + 12345) % 2147483648) / 2147483648);
  const perAsc = new Array(12).fill(0);
  const exact: Array<{ input: any; chart: CanonicalChart }> = [], approx: Array<{ input: any; chart: CanonicalChart }> = [];
  let i = 0;
  while (perAsc.some((n) => n < 28)) {
    const y = 1940 + Math.floor(rnd() * 70), m = 1 + Math.floor(rnd() * 12), d = 1 + Math.floor(rnd() * 28);
    const hh = Math.floor(rnd() * 24), mm = Math.floor(rnd() * 60);
    const [lat, lng] = PLACES[i++ % PLACES.length];
    const input = { date: `${y}-${pad(m)}-${pad(d)}`, time: `${pad(hh)}:${pad(mm)}`, latitude: lat, longitude: lng };
    const c = computeCanonicalChart(resolveBirthWithCoordinates({ ...input, timeAccuracy: 'exact' }), { calculatedAt: asOf });
    if (perAsc[c.ascendant.signIndex] >= 28) continue;
    perAsc[c.ascendant.signIndex]++;
    exact.push({ input, chart: c });
    if (approx.length < 72 && exact.length % 4 === 0) approx.push({ input, chart: computeCanonicalChart(resolveBirthWithCoordinates({ ...input, time: '12:00', timeAccuracy: 'approximate' }), { calculatedAt: asOf }) });
  }
  return { exact, approx };
}
const pct = (xs: number[], q: number) => { const s = [...xs].sort((a, b) => a - b); return s[Math.min(s.length - 1, Math.floor(q * s.length))]; };
const quote = (t: string) => t.split('\n').map((l) => `> ${l}`).join('\n');
const birth = (x: { input: any; chart: CanonicalChart }) => `${x.input.date} ${x.chart.birth.timeAccuracy === 'exact' ? x.input.time : '(time unknown)'} at ${x.input.latitude}, ${x.input.longitude}; ${x.chart.birth.timeAccuracy === 'exact' ? `Lagna ${x.chart.ascendant.sign}` : 'Lagna not used'}`;

function areaExample(title: string, x: { input: any; chart: CanonicalChart }, domain: LifeDomain): string {
  const ins = buildInsights(x.chart, asOf);
  const d = ins.domains.find((r) => r.domain === domain)!;
  const ex = buildExplanations(buildInterpretationContext(x.chart, asOf, ins)).areas.find((a) => a.domain === domain)!;
  return `### ${title}
Chart: ${birth(x)}.

**Existing verdict:** ${d.verdict} (confidence ${d.confidence}) — **unchanged with the flag on** (confidence changed: no).

**Before (flag off) — what the Life areas card and evidence sheet show:**
${quote([d.conclusion, ...d.supporting.slice(0, 3).map((e) => `✓ ${e.explanation}`), ...d.conflicting.slice(0, 3).map((e) => `✗ ${e.explanation}`)].join('\n'))}

**After (flag on) — "In plain words" at the top of the same sheet:**
${quote([ex.summary, ...ex.supports.map((s) => `Supports: ${s.text}`), ...ex.challenges.map((s) => `Challenges: ${s.text}`), ex.period ?? '', ...ex.yogas, ...ex.uncertainty].filter(Boolean).join('\n'))}

**Supporting calculated facts / evidence:** ${[...ex.supports, ...ex.challenges].map((s) => `\`${s.evidenceId}\``).join(', ') || 'none'}.
**Reliability limits:** ${ex.uncertainty.join(' ') || 'none beyond the interpretive disclosure.'}
`;
}

function run() {
  const { exact, approx } = sample();
  const ctxOf = (c: CanonicalChart) => buildInterpretationContext(c, asOf);
  const out: string[] = [`# PR #105 — before and after (USER_FACING_REASONING_V1)

Generated by \`npx tsx scripts/reasoning/user-facing-examples.ts\` from real deterministic charts (the seed-99
sample; reasoning date ${asOf.toISOString().slice(0, 10)}). No placement is invented: every line below is
computed. **Verdicts and confidence are identical with the flag on and off**; only explanatory text is added.
The new wording is generated from existing evidence; it has **not** been astrologically validated.
Ask and report examples show the deterministic grounding added to the prompt — **not live AI output**.
`];

  const pick = (pred: (x: { input: any; chart: CanonicalChart }) => boolean) => exact.find(pred)!;
  const has = (domain: LifeDomain, f: (d: any) => boolean) => (x: { chart: CanonicalChart }) => f(buildInsights(x.chart, asOf).domains.find((d) => d.domain === domain));
  out.push(areaExample('1. Career interpretation', pick(has('career', (d) => d.supporting.length && d.conflicting.length)), 'career'));
  out.push(areaExample('2. Relationship interpretation', pick(has('relationships', (d) => d.conflicting.length > 0 && d.verdict !== 'Insufficient evidence')), 'relationships'));
  out.push(areaExample('3. Financial interpretation', pick(has('wealth', (d) => d.supporting.some((e: any) => e.source === 'Dasha') || d.conflicting.some((e: any) => e.source === 'Dasha'))), 'wealth'));

  // 4. Strong but challenged planet.
  const sbc = exact.find((x) => ctxOf(x.chart).planets.some((p) => p.strongButChallenged))!;
  const planet = ctxOf(sbc.chart).planets.find((p) => p.strongButChallenged)!;
  const pe = buildExplanations(ctxOf(sbc.chart)).planets.find((p) => p.planet === planet.planet)!;
  const d = sbc.chart.strength.dignities.find((x) => x.planet === planet.planet)!;
  const pos = sbc.chart.planets.find((x) => x.name === planet.planet)!;
  out.push(`### 4. Strong but challenged planet (${planet.planet})
Chart: ${birth(sbc)}.

**Before (flag off) — planet sheet header and evidence rows:**
${quote([`${pos.sign} ${pos.degreeInSign.toFixed(1)}° · ${pos.house}th house · ${pos.nakshatra.name} pada ${pos.nakshatra.pada} · ${d.dignity}${d.combust ? ' · combust' : ''}`, ...planet.areas.flatMap((a) => [...a.supporting.map((s) => `✓ ${s.text}`), ...a.challenging.map((s) => `✗ ${s.text}`)])].join('\n'))}

**After (flag on) — "In plain words":**
${quote([pe.summary, ...pe.points].join('\n'))}

**Facts:** ${planet.factIds.map((f) => `\`${f}\``).join(', ')}. **Verdicts:** unchanged. **Limits:** ${pe.uncertainty.join(' ') || 'none.'}
`);

  // 5. Formed yoga with uncertain effectiveness.
  const yx = exact.find((x) => buildExplanations(ctxOf(x.chart)).yogas.some((y) => y.period && /weaken/.test(y.effectiveness)))
    ?? exact.find((x) => buildExplanations(ctxOf(x.chart)).yogas.some((y) => y.period))!;
  const yex = buildExplanations(ctxOf(yx.chart)).yogas.find((y) => y.period)!;
  out.push(`### 5. Formed yoga with uncertain effectiveness (${yex.name})
Chart: ${birth(yx)}.

**Before (flag off):** the yoga line lists the name only:
${quote(`Yogas: ${Array.from(new Set(yx.chart.yogas.filter((y) => !y.cancelled).map((y) => y.name))).join(', ')}.`)}

**After (flag on) — "Your periods and yogas, explained":**
${quote([yex.formation, yex.contribution, yex.effectiveness, yex.period ?? ''].filter(Boolean).join('\n'))}

**Facts:** \`${yex.id}\`. **Limits:** effectiveness is not assessed; a running period is timing only.
`);

  // 6. Current Mahadasha.
  const mx = exact.find((x) => buildExplanations(ctxOf(x.chart)).periods.some((p) => p.level === 'mahadasha' && p.areas.length >= 2))!;
  const ins6 = buildInsights(mx.chart, asOf);
  const cur = ins6.timeline.find((p) => p.status === 'current')!;
  const pex = buildExplanations(ctxOf(mx.chart, )).periods.find((p) => p.level === 'mahadasha')!;
  out.push(`### 6. Current Mahadasha (${pex.lord})
Chart: ${birth(mx)}.

**Before (flag off) — Dasha timeline "why it matters":**
${quote(cur.whyItMatters)}

**After (flag on):**
${quote(pex.text)}

**Facts:** \`${pex.id}\`. **Limits:** one reading of the period lord is a single factor in every area it touches; it does not make those areas turn out alike, and each area's verdict weighs it with that area's own factors.
`);

  // 7. Approximate birth time.
  const ax = approx[0];
  const ains = buildInsights(ax.chart, asOf);
  const aex = buildExplanations(ctxOf(ax.chart));
  const acar = aex.areas.find((a) => a.domain === 'career')!;
  out.push(`### 7. Approximate birth time
Chart: ${birth(ax)}.

**Existing career verdict:** ${ains.domains.find((x) => x.domain === 'career')!.verdict} (unchanged).

**Before (flag off):**
${quote([ains.domains.find((x) => x.domain === 'career')!.conclusion, ains.timing.note ?? ''].filter(Boolean).join('\n'))}

**After (flag on):**
${quote([acar.summary, ...acar.supports.map((s) => `Supports: ${s.text}`), ...acar.uncertainty, ...aex.periods.map((p) => p.text), ...aex.disclosures].join('\n'))}

**Limits:** no Lagna, house, house lord, divisional chart, house-based yoga or dasha date appears; the same text is produced for every placeholder time on the birth date (tested on 72 charts × 9 times).
`);

  // Ask and report grounding (deterministic, not live AI).
  const ask = pick(has('career', (d) => d.supporting.length && d.conflicting.length));
  const route = routeQuestion('How will my career go?');
  const packetOff = buildEvidencePacket(ask.chart, route, asOf).text;
  const block = groundingBlock(buildExplanations(ctxOf(ask.chart)), { domains: route.domains, planets: route.planets, evidenceLines: false });
  out.push(`### Ask your Kundli — grounding added to the prompt (deterministic; not a generated answer)
Question: "How will my career go?" on the career example chart. With the flag on, this block is appended to the
existing evidence packet (${packetOff.length} characters before); the answer guard checks the reply exactly as before.

\`\`\`text
${block}
\`\`\`
`);

  // Performance.
  const time = (f: () => void) => { const t = performance.now(); f(); return performance.now() - t; };
  for (const { chart } of exact.slice(0, 30)) ctxOf(chart);
  const perf: Record<string, { ctx: number[]; ask: number[]; report: number[]; payload: number[]; lifeWhole: number[]; lifeSections: number[] }> = {};
  for (const [set, tag] of [[exact, 'exact'], [approx, 'approximate']] as const) {
    const p = (perf[tag] = { ctx: [], ask: [], report: [], payload: [], lifeWhole: [], lifeSections: [] });
    for (const { chart } of set) {
      const ins = buildInsights(chart, asOf);
      p.ctx.push(time(() => buildExplanations(buildInterpretationContext(chart, asOf, ins))));
      const ex = buildExplanations(buildInterpretationContext(chart, asOf, ins));
      p.ask.push(groundingBlock(ex, { domains: ['career'], evidenceLines: false }).length + 2);
      p.report.push(groundingBlock(ex).length + 2);
      // Complete Life Report: the whole block in every one of its batches, against each batch's own section.
      p.lifeWhole.push(LIFE_REPORT_GROUNDING_PLAN.length * (groundingBlock(ex).length + 2));
      p.lifeSections.push(LIFE_REPORT_GROUNDING_PLAN.reduce((n, b) => n + sectionGroundingBlock(ex, b.grounding).length + 2, 0));
      p.payload.push(JSON.stringify(ex).length);
    }
  }
  const row = (tag: string, k: 'ctx' | 'ask' | 'report' | 'payload' | 'lifeWhole' | 'lifeSections', unit: string, f = (n: number) => n.toFixed(2)) => `| ${tag} | ${unit} | ${f(pct(perf[tag][k], 0.5))} | ${f(pct(perf[tag][k], 0.95))} |`;
  const tok = (n: number) => `${n} chars ≈ ${Math.round(n / 4)} tokens`;
  out.push(`## Performance (seed 99, after warm-up)

| Set | Measure | Median | p95 |
|---|---|---|---|
${row('exact', 'ctx', 'context + explanations build (ms, reusing the request\'s insights)')}
${row('approximate', 'ctx', 'context + explanations build (ms, reusing the request\'s insights)')}
${row('exact', 'ask', 'Ask prompt addition, one area', tok)}
${row('approximate', 'ask', 'Ask prompt addition, one area', tok)}
${row('exact', 'report', 'report prompt addition, all areas', tok)}
${row('approximate', 'report', 'report prompt addition, all areas', tok)}
${row('exact', 'lifeWhole', `Complete Life Report, ${LIFE_REPORT_GROUNDING_PLAN.length} batches, whole block in each (before)`, tok)}
${row('exact', 'lifeSections', `Complete Life Report, ${LIFE_REPORT_GROUNDING_PLAN.length} batches, each batch's own section (after)`, tok)}
${row('exact', 'payload', 'Insights payload addition (bytes)', (n) => String(n))}
${row('approximate', 'payload', 'Insights payload addition (bytes)', (n) => String(n))}

No additional AI call is made: the block is part of the existing single explainer call and report calls.
Token counts are estimated at four characters per token. Generation latency of the live model was not measured here
(no model call is made by this script); the added input tokens are the only change to a model request.
`);
  writeFileSync('docs/reasoning/PR105_BEFORE_AFTER.md', out.join('\n'));
  console.log(JSON.stringify(Object.fromEntries(Object.entries(perf).map(([k, v]) => [k, { ctxMedian: pct(v.ctx, 0.5), ctxP95: pct(v.ctx, 0.95), askMedian: pct(v.ask, 0.5), reportMedian: pct(v.report, 0.5), payloadMedian: pct(v.payload, 0.5) }]))));
}

run();
